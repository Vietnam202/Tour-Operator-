'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const js=fs.readFileSync('vta-ai-itinerary-editor.js','utf8');
const ui=fs.readFileSync('document-editor.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const mock={window:{}};
vm.runInNewContext(js,mock,{timeout:1000});
assert.equal(typeof mock.window.VTAItineraryAI?.open,'function');
assert.equal(typeof mock.window.VTAItineraryAI?.baseDraft,'function');
const ctx={costing_revision:'rev-fixed',program:{id:7,title:'Hanoi 7D6N',days:[{day:1,title:'Hanoi',notes:'INTERNAL NOTES NEVER FOR LLM'}],proposal:{private_prices:[]}}};
const d=mock.window.VTAItineraryAI.baseDraft(ctx,{getJSON:()=>({type:'doc',content:[{type:'paragraph'}]})});
assert.deepEqual(Array.from(d.private_groups.map(x=>x.pax)),[4,6,8,10,12]);
assert.equal(d.private_groups[0].prices['3star'],null);
assert.equal(d.days[0].notes,'','internal notes removed from AI payload');
assert.equal(d.source_program_id,7);
assert.equal(d.source_revision,'rev-fixed');
assert.equal(d.selling_prices_reviewed,false);
assert.equal(d.currency,'USD');
assert.equal(d.schema,'VTA_MASTER_ITINERARY_V1');
assert(ui.includes("btn('ai-itinerary','AI Edit Itinerary'"),'Master editor must expose AI editing');
assert(ui.includes('if(dirty||saving)throw Error('),'unsaved changes must block AI review');
assert(html.includes('vta-ai-itinerary-editor.js?v=VIE16-AI-1'),'new module must load before editor');
assert(fs.readFileSync('preview.html','utf8').includes('vta-ai-itinerary-editor.js?v=VIE16-AI-1'),'preview must load identical module versions');
assert(js.includes("tour-library/'+libraryProgram.id+'/ai-edit/preview"),'preview goes to authenticated server API');
assert(js.includes("tour-library/'+libraryProgram.id+'/ai-edit/commit"),'commit goes to audited draft API');
assert(js.includes("creation_key:creationKey"),'commit must include idempotency key');
assert(js.includes('data-ai-ack'),'human review checkbox required');
assert(js.includes('api.request('),'never invoke direct unauthenticated external model API');
console.log('PASS VIE-16 AI editor UI contract (five groups, source revision, review/preview, immutable draft, no internal notes).');
