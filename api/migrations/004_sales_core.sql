SET NAMES utf8mb4;
SET time_zone = '+07:00';

CREATE TABLE IF NOT EXISTS customers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  company_id BIGINT UNSIGNED NOT NULL,
  customer_ref VARCHAR(64) NOT NULL,
  customer_type ENUM('DIRECT','B2B_CONTACT') NOT NULL DEFAULT 'DIRECT',
  full_name VARCHAR(190) NOT NULL,
  company_name VARCHAR(190) NULL,
  country VARCHAR(120) NULL,
  market VARCHAR(120) NULL,
  whatsapp VARCHAR(64) NULL,
  email VARCHAR(190) NULL,
  preferred_language VARCHAR(80) NULL,
  source VARCHAR(80) NULL,
  notes TEXT NULL,
  sales_owner_id BIGINT UNSIGNED NULL,
  status ENUM('ACTIVE','INACTIVE','ARCHIVED') NOT NULL DEFAULT 'ACTIVE',
  version_no INT UNSIGNED NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NOT NULL,
  updated_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  archived_at DATETIME NULL,
  UNIQUE KEY uq_customer_ref(company_id,customer_ref),
  KEY idx_customer_name(company_id,full_name),
  KEY idx_customer_contact(company_id,whatsapp,email),
  CONSTRAINT fk_customer_company FOREIGN KEY(company_id) REFERENCES companies(id),
  CONSTRAINT fk_customer_owner FOREIGN KEY(sales_owner_id) REFERENCES users(id),
  CONSTRAINT fk_customer_created FOREIGN KEY(created_by) REFERENCES users(id),
  CONSTRAINT fk_customer_updated FOREIGN KEY(updated_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

