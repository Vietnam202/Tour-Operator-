CREATE TABLE IF NOT EXISTS quote_cost_items (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  quote_version_id BIGINT UNSIGNED NOT NULL,
  sort_order INT UNSIGNED NOT NULL DEFAULT 0,
  category ENUM('TRANSPORT','GUIDE','HOTEL','MEAL','ATTRACTION','TOUR','CRUISE','VISA','OTHER') NOT NULL DEFAULT 'OTHER',
  service_name VARCHAR(255) NOT NULL,
  service_date DATE NULL,
  pax DECIMAL(10,2) NOT NULL DEFAULT 1,
  qty DECIMAL(10,2) NOT NULL DEFAULT 1,
  unit_price DECIMAL(18,2) NOT NULL DEFAULT 0,
  currency CHAR(3) NOT NULL DEFAULT 'VND',
  total DECIMAL(18,2) NOT NULL DEFAULT 0,
  supplier_id BIGINT UNSIGNED NULL,
  rate_id BIGINT UNSIGNED NULL,
  rate_version_id BIGINT UNSIGNED NULL,
  source_document_id BIGINT UNSIGNED NULL,
  source_type ENUM('APPROVED_RATE','SPECIAL_QUOTE','MANUAL','LEGACY') NOT NULL DEFAULT 'MANUAL',
  manual_pax TINYINT(1) NOT NULL DEFAULT 0,
  notes VARCHAR(1000) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_qci_quote(quote_version_id,sort_order),
  CONSTRAINT fk_qci_version FOREIGN KEY(quote_version_id) REFERENCES quote_versions(id) ON DELETE CASCADE,
  CONSTRAINT fk_qci_supplier FOREIGN KEY(supplier_id) REFERENCES suppliers(id),
  CONSTRAINT fk_qci_rate FOREIGN KEY(rate_id) REFERENCES rates(id),
  CONSTRAINT fk_qci_rate_version FOREIGN KEY(rate_version_id) REFERENCES rate_versions(id),
  CONSTRAINT fk_qci_doc FOREIGN KEY(source_document_id) REFERENCES documents(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

